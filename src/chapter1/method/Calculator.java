package chapter1.method;

public class Calculator {

    // 메서드 선언 - 두 수를 더합니다.
    int sum(int value1, int value2) {
        int result = value1 + value2;
        return result;
    }

    int minus(int value1, int value2) {
        int result = value1 - value2;
        return result;
    }

    int mult(int value1, int value2) {
        int result = value1 * value2;
        return result;
    }

    int div(int value1, int value2) {
        int result = value1 / value2;
        return result;
    }

}

